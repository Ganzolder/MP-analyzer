/**
 * Определяет группу для типа начисления
 * Использует частичное совпадение, если точное не найдено
 */
export function getChargeGroup(chargeType: string): string {
  if (!chargeType) return "Прочее";
  
  // Сначала проверяем точное совпадение
  if (CHARGE_TYPE_TO_GROUP[chargeType]) {
    return CHARGE_TYPE_TO_GROUP[chargeType];
  }
  
  // Проверяем частичное совпадение (для случаев с дополнительными символами или пробелами)
  const normalizedType = chargeType.trim();
  for (const [key, group] of Object.entries(CHARGE_TYPE_TO_GROUP)) {
    if (normalizedType.includes(key) || key.includes(normalizedType)) {
      return group;
    }
  }
  
  return "Прочее";
}

/**
 * Получить список всех типов начислений для группы
 */
export function getChargeTypesForGroup(groupName: string): string[] {
  return Object.entries(CHARGE_TYPE_TO_GROUP)
    .filter(([_, group]) => group === groupName)
    .map(([chargeType, _]) => chargeType);
}
