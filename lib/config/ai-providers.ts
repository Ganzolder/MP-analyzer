export const DEFAULT_PROVIDER: AIProviderKey = "google";

/**
 * Получение конфигурации провайдера
 */
export function getProviderConfig(provider: AIProviderKey): AIProviderConfig {
  return AI_PROVIDERS[provider] || AI_PROVIDERS[DEFAULT_PROVIDER];
}

/**
 * Проверка доступности провайдера
 * ВАЖНО: Работает только на сервере (Node.js), на клиенте всегда возвращает false
 */
export function isProviderAvailable(provider: AIProviderKey): boolean {
  // На клиенте (браузер) process.env недоступен, возвращаем false
  if (typeof window !== "undefined") {
    return false;
  }
  
  const config = AI_PROVIDERS[provider];
  if (!config || !config.available) return false;
  
  // Проверка наличия API ключа (только на сервере)
  if (typeof process !== "undefined" && config.apiKeyEnv) {
    return !!process.env[config.apiKeyEnv];
  }
  
  return false;
}

