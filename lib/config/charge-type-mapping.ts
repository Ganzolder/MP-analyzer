/**
 * Определяет группу для типа начисления
 * @param chargeType - Тип начисления из файла
 * @returns Название группы или null, если группа не найдена (тогда тип остаётся без группы)
 */
export function getGroupForChargeType(chargeType: string): string | null {
  if (!chargeType) return null;
  
  const normalizedType = chargeType.trim().toLowerCase();
  
  // Проверяем точное совпадение или совпадение по подстроке
  // Важно: проверяем в обратном порядке (самые длинные паттерны сначала)
  // для более точного маппинга
  const sortedMappings = [...CHARGE_TYPE_TO_GROUP_MAP].reverse();
  
  for (const mapping of sortedMappings) {
    for (const pattern of mapping.patterns) {
      const normalizedPattern = pattern.toLowerCase();
      
      // Точное совпадение (без учёта регистра)
      if (normalizedType === normalizedPattern) {
        return mapping.group;
      }
      // Совпадение по подстроке: тип начисления должен содержать паттерн
      if (normalizedType.includes(normalizedPattern)) {
        return mapping.group;
      }
    }
  }
  
  // Если группа не найдена, возвращаем null (тип остаётся как есть)
  return null;
}

/**
 * Проверяет, относится ли тип начисления к какой-либо группе
 */
export function hasGroup(chargeType: string): boolean {
  return getGroupForChargeType(chargeType) !== null;
}
